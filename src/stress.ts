// Stress test: random rota changes the checks never saw, run through the gate's code checks and compared
// with the hand-written reference rules (src/reference.ts). No API key, no network; the seed makes it repeatable.
// Usage: pnpm stress [count] [seed]
import { writeFileSync } from "node:fs";
import type { Rota, ShiftKind } from "./domain.js";
import { applyChange, type Change } from "./examples.js";
import { runChecks } from "./gate.js";
import { baseWeek } from "./ollies.js";
import { reference } from "./reference.js";

const COUNT = Number(process.argv[2] ?? 10000);
const SEED = Number(process.argv[3] ?? 42);

// mulberry32: small, fast, and the same numbers on every machine.
function rng(seed: number): () => number {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

const rand = rng(SEED);
const pick = <T>(xs: readonly T[]): T => xs[Math.floor(rand() * xs.length)]!;
const hhmm = (minutes: number) => `${String(Math.floor(minutes / 60)).padStart(2, "0")}:${String(minutes % 60).padStart(2, "0")}`;

const base = baseWeek();
const staffIds = base.staff.map((p) => p.id);
const KINDS: ShiftKind[] = ["open", "mid", "close"];

/** One to three edits a rota assistant might make: drop a shift, add a standard one, or add one with odd hours. */
function randomChange(): Change {
  const remove = new Set<string>();
  const add: NonNullable<Change["add"]> = [];
  const edits = 1 + Math.floor(rand() * 3);
  for (let i = 0; i < edits; i++) {
    const r = rand();
    if (r < 0.4) remove.add(pick(base.shifts).id);
    else if (r < 0.75) add.push({ staffId: pick(staffIds), day: Math.floor(rand() * 7), kind: pick(KINDS) });
    else {
      const start = 6 * 60 + 30 * Math.floor(rand() * 26); // 06:00 to 18:30
      const length = 60 * (2 + Math.floor(rand() * 9)); // 2 to 10 hours
      add.push({ staffId: pick(staffIds), day: Math.floor(rand() * 7), kind: pick(KINDS), start: hhmm(start), end: hhmm(Math.min(start + length, 21 * 60)) });
    }
  }
  return { remove: [...remove], add };
}

type RuleId = keyof typeof reference;
const rules = Object.keys(reference) as RuleId[];

let bad = 0, stopped = 0, good = 0, wronglyStopped = 0;
const perRule = Object.fromEntries(rules.map((r) => [r, { broken: 0, caught: 0, falseAlarms: 0 }])) as Record<RuleId, { broken: number; caught: number; falseAlarms: number }>;
const misses: { change: Change; rule: string; kind: "missed" | "false alarm" }[] = [];

for (let i = 0; i < COUNT; i++) {
  const change = randomChange();
  const rota: Rota = applyChange(change, base);
  const results = await runChecks(rota);
  const gateStops = results.some((r) => r.violations.length > 0);
  const refBroken = rules.filter((r) => !reference[r](rota));

  if (refBroken.length) { bad++; if (gateStops) stopped++; }
  else { good++; if (gateStops) wronglyStopped++; }

  for (const r of rules) {
    const flagged = (results.find((x) => x.ruleId === r)?.violations.length ?? 0) > 0;
    const broken = refBroken.includes(r);
    if (broken) { perRule[r].broken++; if (flagged) perRule[r].caught++; else misses.push({ change, rule: r, kind: "missed" }); }
    else if (flagged) { perRule[r].falseAlarms++; misses.push({ change, rule: r, kind: "false alarm" }); }
  }
}

const pct = (n: number, d: number) => (d === 0 ? "n/a" : `${((100 * n) / d).toFixed(1)}%`);
const lines = [
  "# Stress test",
  "",
  `Generated by \`pnpm stress ${COUNT} ${SEED}\`. ${COUNT} random rota changes (one to three edits each: a shift dropped, a standard shift added, or a shift with odd hours added) to Ollie's normal week. None of them is one of the owner's example weeks the checks were proven on.`,
  "",
  "Each changed week goes through the gate's code checks, the TypeScript Claude wrote from the interview. The answer key is a second, hand-written version of the same five rules (`src/reference.ts`). The AI-judged rule (weekend fairness) is left out: it needs an API key, and its verdicts aren't deterministic.",
  "",
  "| | Weeks | Gate result |",
  "|---|---|---|",
  `| Break at least one rule | ${bad} | ${stopped} stopped (${pct(stopped, bad)}) |`,
  `| Break no rule | ${good} | ${wronglyStopped} wrongly stopped (${pct(wronglyStopped, good)}) |`,
  "",
  "| Rule | Weeks breaking it | Caught by its check | False alarms |",
  "|---|---|---|---|",
  ...rules.map((r) => `| ${r} | ${perRule[r].broken} | ${perRule[r].caught} (${pct(perRule[r].caught, perRule[r].broken)}) | ${perRule[r].falseAlarms} |`),
  "",
  misses.length ? `## Disagreements (first 10 of ${misses.length})\n\n${misses.slice(0, 10).map((m) => `- ${m.kind}, ${m.rule}: \`${JSON.stringify(m.change)}\``).join("\n")}` : "No disagreements: every check matched the hand-written rule on every week.",
  "",
];
writeFileSync("docs/stress-test.md", lines.join("\n"));
console.log(lines.join("\n"));
// Any disagreement fails the run, so CI catches a check that drifts from the rule.
if (misses.length) process.exitCode = 1;
